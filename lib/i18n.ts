/**
 * Get localized string by key with automatic fallback to English,
 * then to the provided fallback string, and finally to the key itself.
 */
export function getMessage(locale: string, key: string, fallback?: string): string {
  const loc = (locale || 'en').toLowerCase();
  return messages[loc]?.[key] ?? messages.en?.[key] ?? fallback ?? key;
}

/**
 * Check if a locale has translations configured.
 */
export function hasLocale(locale: string): boolean {
  return Boolean(messages[locale.toLowerCase()]);
}
